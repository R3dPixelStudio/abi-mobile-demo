const phoneProducts: Product[] = phones.map(
  (
    [
      id,
      name,
      brand,
      price,
      display,
      chip,
      camera,
      battery,
      storage,
      os,
      color,
      colorHex,
      extension,
    ],
    index,
  ) => {
    const image = extension
      ? `/products/${id}.${extension}`
      : `/products/${id}-unavailable.svg`;
    const capacities = storage
      .split(" / ")
      .map((value) =>
        value.includes("گیگابایت") ? value : `${value} گیگابایت`,
      );
    const description = `${name}؛ با نمایشگر ${display} و تراشه ${chip}. مشخصات برای نسخه معرفی‌شده درج شده‌اند؛ رنگ، حافظه، مدل منطقه‌ای و محتویات جعبه را پیش از سفارش بررسی کنید. قیمت و موجودی این فروشگاه آزمایشی است.`;
    return {
      id,
      slug: id,
      name,
      brand,
      kind: "phone",
      category: "گوشی موبایل",
      description,
      images: [image],
      imageAlt: extension
        ? `تصویر مدل ${name}؛ رنگ تصویر ممکن است با انتخاب شما متفاوت باشد`
        : `تصویر تأییدشده ${name} هنوز آماده نیست`,
      specs: {
        نمایشگر: display,
        تراشه: chip,
        دوربین: camera,
        باتری: battery,
        حافظه: storage,
        سیستم‌عامل: os,
      },
      variants: [
        {
          id: `${id}-1`,
          color,
          colorHex,
          storage: capacities[0],
          price,
          stock: index === 15 ? 0 : 4 + (index % 7),
        },
        {
          id: `${id}-2`,
          color: "مشکی",
          colorHex: "#252528",
          storage: capacities[1] || capacities[0],
          price: price + (capacities[1] ? 4500000 : 500000),
          stock: index % 4 === 0 || index === 15 ? 0 : 3,
        },
      ],
      featured: [0, 4, 8, 16].includes(index),
      offer: [2, 6, 10, 18].includes(index),
      seo: { title: `${name} | مشخصات و انتخاب ظرفیت`, description, image },
    };
  },
);

